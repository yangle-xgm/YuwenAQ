"""提示词模板库（2.3 优化提示词改善回答质量）。

本文件把"人设 + 回答规矩 + 知识占位符 + 问题占位符"收口成结构化模板，
替代 core.py 里原先写死的字符串拼接。对应 2.3 文档的两个核心手法：
  1) 第五段「提示词模板」：钉死人设与回答规范，留 {context}/{query} 两个填空位；
  2) 第七、八段「结构化任务书」：用【任务要求】/【输出要求】/【用户输入】三段式
     + 分隔线，把"要做什么 / 怎么交卷 / 素材是什么"隔离清楚，并可约束输出格式。

所有模板都用 str.format 的 {name} 占位符，调用方只填值、不动模板结构。
"""
from ..config import SYSTEM_PROMPT


# ---------------------------------------------------------------- 1) 系统提示词模板（RAG 问答主路径）
# 结构：人设 → 【回答规范】九条 → 参考知识块（占位）→ 用户问题（占位）→ "回答："
# 注意：SYSTEM_PROMPT 作为人设原样拼在最前（不含占位符），format 只替换下面两个字段。
SYSTEM_TEMPLATE = (
    SYSTEM_PROMPT + "\n\n"
    "【回答规范】：\n"
    "1. 必须严格依据下方“参考知识”作答，不得凭空编造课程标准中没有的内容。\n"
    "2. 若参考知识中找不到答案，如实说明“知识库暂未覆盖该问题”，不要硬编。\n"
    "3. 涉及量化事实（识字量、阅读量、学段要求等）：若参考知识中给出了具体数字，必须引用；"
    "若参考知识未给出具体数字，请勿臆造数字，只描述对应的能力要求或评价要点。\n"
    "4. 尽量标注出处（如“据第三学段要求”“见课程目标”）。\n"
    "5. 回答要完整而有条理：问题涉及多个要点时逐条列出，每条给出依据或适用范围；"
    "同时不展开与问题无关的内容。\n"
    # 术语原词约束。实测：7B 仍会把“语言运用”说成“语言”、“审美创造”说成“审美”，
    # 即使知识块里四个原词齐全——属模型能力限制，提示词挡不住（同 2.10 的教训）。
    # 保留该条作为对更强模型的约束，不指望 7B 遵守。
    "6. 引用课标术语时使用原文表述（如“语言运用”“审美创造”“文化自信”“思维能力”），"
    "不要简写、缩写或改写成近义词。\n"
    "7. 消息中已包含此前的对话历史；若当前问题是追问或使用指代（它/那/这个/同样），"
    "请结合历史理解其真实含义后再作答，不要当成孤立的新问题。\n"
    "8. 本知识库只收录《义务教育语文课程标准（2022 年版）》，覆盖小学一年级至初中九年级"
    "（第一至第四学段）。若问题涉及高中、学前、大学等其他学段，必须明确说明“超出本知识库"
    "覆盖范围”，并提示可参阅《普通高中语文课程标准》；严禁用通用经验或模型自身知识代替课标要求。\n"
    "9. 本知识库只收录课程标准条文，**不包含范文、例文或作文示例**。若用户索要“范文/范本”，"
    "必须先说明“课标未收录范文”，再给出“依据第 X 学段写作要求编写的参考示例”，"
    "并明确它是示例而非课标原文；示例须贴合该学段的字数与表达要求"
    "（如第四学段 45 分钟不少于 500 字、要有真情实感、围绕中心安排详略），不要堆砌辞藻。\n\n"
    "以下是参考知识（来自《语文课程标准》）：\n"
    "---------------------\n"
    "{context}\n"
    "---------------------\n\n"
    "用户问题：{query}\n"
    "回答："
)


def build_system_prompt(query: str, knowledge: str) -> str:
    """把检索到的知识块和用户问题填进系统提示词模板。

    参数:
        query: 用户这一轮的问题。
        knowledge: 检索器召回并已格式化好的知识文本（多个片段用空行分隔）；
                   无知识库时传空串，则只保留人设与规范（纯模型问答模式）。
    返回: 完整 system prompt 字符串。
    """
    return SYSTEM_TEMPLATE.format(context=knowledge or "（暂无参考知识）", query=query)


# ---------------------------------------------------------------- 2) 结构化任务书模板（约束输出 / 创作 / 审查）
# 对应 2.3 第七、八段：把"任务说明 / 输出格式 / 用户素材"三段用分隔线隔开，
# 模型不易把"输出要求"误当成"要处理的内容"。换任务只改这三块文字，结构不变。
TASK_BOOK_TEMPLATE = (
    "【任务要求】\n{task}\n"
    "---------------------\n"
    "【输出要求】\n{output}\n"
    "---------------------\n"
    "【用户输入】\n{user_input}"
)


def build_task_book(task: str, output: str, user_input: str) -> str:
    """拼一份结构化任务书（2.3 第七、八段的可复用骨架）。

    参数:
        task:       要模型做什么（如"审查错别字""按主题创作"）。
        output:     要模型怎么交卷（如"只输出 JSON，字段 label/reason/correct""输出 Markdown"）。
        user_input: 实际素材（待审文本 / 创作主题 / 待翻译原文……）。
    返回: 拼好的任务书字符串，可直接作为 prompt 发给模型。
    """
    return TASK_BOOK_TEMPLATE.format(task=task, output=output, user_input=user_input)
